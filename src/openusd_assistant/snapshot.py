"""Rebuild the corpus manifest from every RST file in docs/ at the pinned commit."""

import hashlib
import json
from collections import Counter
from collections.abc import Callable
from pathlib import Path, PurePosixPath
from urllib.request import Request

from .corpus import (
    _DOCUMENT,
    _MAX_SOURCE_BYTES,
    _NOTICES,
    _REPOSITORY,
    Manifest,
    _NoRedirect,
    build_opener,
    document_title,
)
from .models import Chunk

ListTree = Callable[[str], list[str]]
ReadFile = Callable[[str, str], bytes]


def build_manifest(
    current: dict,
    list_tree: ListTree,
    read_file: ReadFile,
    *,
    snapshot_dir: Path | None = None,
) -> dict:
    """Return a manifest for all docs/**/*.rst at ``current['commit']``.

    Repository, release, commit and license are kept from the current manifest so the
    corpus can only grow within the same pinned snapshot.
    """
    commit = current["commit"]
    paths = sorted(
        path for path in list_tree(commit) if path.startswith("docs/") and path.endswith(".rst")
    )
    rejected = [path for path in paths if not _DOCUMENT.fullmatch(path)]
    if rejected:
        raise ValueError(f"Unsupported documentation paths: {', '.join(rejected)}")
    if not paths:
        raise ValueError("The pinned commit has no RST documentation")

    def entry(path: str) -> tuple[dict, bytes]:
        content = read_file(commit, path)
        if len(content) > _MAX_SOURCE_BYTES:
            raise ValueError(f"{path} exceeds the source size limit")
        if snapshot_dir is not None:
            target = snapshot_dir.joinpath(*PurePosixPath(path).parts)
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content)
        return {"path": path, "sha256": hashlib.sha256(content).hexdigest()}, content

    documents = []
    for path in paths:
        record, content = entry(path)
        title = document_title(content.decode("utf-8"), PurePosixPath(path).stem)
        documents.append({"path": path, "title": title, "sha256": record["sha256"]})
    notices = [entry(path)[0] for path in sorted(_NOTICES)]
    return {
        "repository": current["repository"],
        "release": current["release"],
        "commit": commit,
        "license": current["license"],
        "documents": documents,
        "notices": notices,
    }


def github_tree(commit: str) -> list[str]:
    url = f"https://api.github.com/repos/{_REPOSITORY}/git/trees/{commit}?recursive=1"
    request = Request(url, headers={"Accept": "application/vnd.github+json"})
    with build_opener(_NoRedirect).open(request, timeout=30) as response:
        data = json.load(response)
    if data.get("truncated"):
        raise ValueError("GitHub returned a truncated tree; the file list would be incomplete")
    return [item["path"] for item in data["tree"] if item["type"] == "blob"]


def github_file(commit: str, path: str) -> bytes:
    url = f"https://raw.githubusercontent.com/{_REPOSITORY}/{commit}/{path}"
    with build_opener(_NoRedirect).open(url, timeout=30) as response:
        return response.read(_MAX_SOURCE_BYTES + 1)


def corpus_report(manifest: Manifest, chunks: list[Chunk], *, largest: int = 5) -> str:
    """Summarize file and chunk counts so corpus changes are visible in review."""
    per_file = Counter(chunk.path for chunk in chunks)
    sizes = sorted(len(chunk.text) for chunk in chunks)
    empty = [file.path for file in manifest.documents if not per_file[file.path]]

    def pct(q: float) -> int:
        return sizes[min(len(sizes) - 1, int(q * len(sizes)))]

    rows = [
        f"# Corpus: OpenUSD {manifest.release}",
        "",
        f"Commit `{manifest.commit}`. Generated by `openusd-assistant check-corpus --report`.",
        "",
        "| Measure | Value |",
        "| --- | --- |",
        f"| RST documents | {len(manifest.documents)} |",
        f"| Documents with chunks | {len(per_file)} |",
        f"| Chunks | {len(chunks)} |",
        f"| Chunk characters p50 / p95 / max | {pct(0.5)} / {pct(0.95)} / {sizes[-1]} |",
        "",
        "Documents without chunks (only headings, toctree or include directives): "
        + (", ".join(f"`{path}`" for path in empty) or "none"),
        "",
        "| Most chunks | Count |",
        "| --- | --- |",
        *(f"| `{path}` | {count} |" for path, count in per_file.most_common(largest)),
        "",
        "| Largest chunks | Lines | Characters |",
        "| --- | --- | --- |",
        *(
            f"| `{c.path}` | {c.start_line}–{c.end_line} | {len(c.text)} |"
            for c in sorted(chunks, key=lambda c: -len(c.text))[:largest]
        ),
    ]
    return "\n".join(rows) + "\n"
